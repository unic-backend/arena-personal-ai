const DICTS: Record<Lang, Dict> = { en, fr };

/* ── locale store ── */

const LOCALE_KEY = 'usman.locale.v1';

function initialLocale(): Lang {
  try {
    const saved = localStorage.getItem(LOCALE_KEY);
    if (saved === 'fr' || saved === 'en') return saved;
  } catch { /* ignore */ }
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

interface I18nState {
  locale: Lang;
  setLocale(l: Lang): void;
  t(key: string, vars?: Record<string, string | number>): string;
}

export const useI18n = create<I18nState>((set, get) => ({
  locale: initialLocale(),
  setLocale: (l) => {
    try { localStorage.setItem(LOCALE_KEY, l); } catch { /* ignore */ }
    set({ locale: l });
  },
  t: (key, vars) => {
    const { locale } = get();
    let str = DICTS[locale][key] ?? DICTS.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) str = str.replace(`{${k}}`, String(v));
    return str;
  },
}));

/** non-react accessor (backend/adapters) */
export function uiLocale(): Lang {
  return useI18n.getState().locale;
}
