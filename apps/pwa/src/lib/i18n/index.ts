/* ── message language heuristic ── */

const FR_WORDS = new Set([
  'le', 'la', 'les', 'des', 'une', 'un', 'est', 'sont', 'était', 'que', 'qui', 'quoi', 'dans',
  'pour', 'sur', 'avec', 'mon', 'ma', 'mes', 'ton', 'ta', 'tes', 'son', 'sa', 'ses', 'te', 'tu',
  'vous', 'nous', 'je', 'il', 'elle', 'on', 'et', 'ou', 'mais', 'pas', 'plus', 'du', 'au', 'aux',
  'ce', 'cette', 'ces', 'se', 'si', 'y', 'en', 'ne', 'fais', 'faire', 'peux', 'corrige',
  'corriger', 'répare', 'réparer', 'analyse', 'analyser', 'projet', 'erreur', 'erreurs',
  'build', 'compilation', 'cherche', 'recherche', 'derniers', 'dernières', 'dernier', 'dernière',
  'actualités', 'nouveautés', 'exécute', 'lance', 'calcule', 'combien', 'vaut', 'parle',
  'comment', 'pourquoi', 'quand', 'où', 'quel', 'quelle', 'merci', 'salut', 'bonjour', 'bonsoir',
  'coucou', 'fonctionne', 'marche', 'affiche', 'montre', 'liste', 'lis', 'fichier', 'fichiers',
]);

const EN_WORDS = new Set([
  'and', 'or', 'but', 'not', 'my', 'me', 'you', 'your', 'please', 'can', 'could', 'would',
  'should', 'fix', 'search', 'find', 'look', 'run', 'execute', 'compute', 'calculate', 'show',
  'list', 'read', 'file', 'files', 'error', 'errors', 'failing', 'broken', 'thanks', 'thank',
  'hello', 'hey', 'hi', 'hey', 'does', 'do', 'did', 'have', 'has', 'want', 'need', 'me',
]);

export function detectLanguage(text: string): Lang | null {
  let fr = 0;
  let en = 0;
  if (/[àâäçèéêëîïôöùûüÿ]/i.test(text)) fr += 2;
  if (/\b(c'est|j'ai|je suis|n'est|l'|d'|qu')/i.test(text)) fr += 2;
  const toks = text
    .toLowerCase()
    .split(/[^a-zàâäçèéêëîïôöùûüÿ0-9']+/i)
    .filter(Boolean);
  for (const t of toks) {
    if (FR_WORDS.has(t)) fr++;
    if (EN_WORDS.has(t)) en++;
  }
  if (fr === en) return null;
  return fr > en ? 'fr' : 'en';
}

